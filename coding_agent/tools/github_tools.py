import os
import re
import subprocess
from pathlib import Path
from typing import Optional, Dict, Any
import requests

from .repository_tools import _get_target_repo, _git


def _get_setting(name: str, default: str = "") -> str:
    """Retrieve setting from environment or GitHub Action INPUT_* variable."""
    return (
        os.getenv(name)
        or os.getenv(f"INPUT_{name.upper()}")
        or os.getenv(name.upper())
        or default
    ).strip()


def _parse_repo_slug(repo: Path) -> Optional[str]:
    """Extract owner/repo from GITHUB_REPOSITORY or git remote origin URL."""
    env_slug = _get_setting("GITHUB_REPOSITORY")
    if env_slug and "/" in env_slug:
        return env_slug

    remote = _git(repo, "remote", "get-url", "origin")
    if remote.returncode == 0:
        url = remote.stdout.strip()
        # Match git@github.com:owner/repo.git or https://github.com/owner/repo.git
        match = re.search(r"github\.com[/:]([A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+?)(?:\.git)?$", url)
        if match:
            return match.group(1)
    return None


def push_and_create_pull_request(
    issue_key: str,
    summary: str = "",
    description: str = "",
    acceptance_criteria: str = "",
    changes_summary: str = "",
    test_summary: str = "",
    base_branch: str = "main",
) -> dict:
    """Push the feature branch to origin and create a GitHub Pull Request for human review.

    Args:
        issue_key: The Jira ticket number (e.g. 'DEMO-1').
        summary: Title/summary of the Jira issue.
        description: Full requirements/description from Jira.
        acceptance_criteria: Acceptance criteria from Jira.
        changes_summary: High-level explanation of the code changes made by the agent.
        test_summary: Summary of test suite results and verification.
        base_branch: Target base branch for PR (defaults to 'main').
    """
    clean_key = (issue_key or "").strip()
    match = re.search(r"([A-Z][A-Z0-9_]+-\d+)", clean_key)
    if match:
        clean_key = match.group(1)

    repo = _get_target_repo()
    if not (repo / ".git").exists():
        return {"error": "Target repository is not a Git repository."}

    curr_branch = _git(repo, "branch", "--show-current").stdout.strip()
    branch = clean_key if clean_key else curr_branch

    # Retrieve GitHub token and repository slug
    token = _get_setting("GITHUB_TOKEN") or _get_setting("GH_TOKEN")
    repo_slug = _parse_repo_slug(repo) or "sample-org/sample-springboot-app"

    # Check for dry run / mock / offline mode
    is_dry_run = (
        _get_setting("DRY_RUN").lower() in ("true", "1", "yes")
        or _get_setting("MOCK_GITHUB").lower() in ("true", "1", "yes")
        or _get_setting("MOCK_MODE").lower() in ("true", "1", "yes")
    )

    jira_base_url = _get_setting("JIRA_BASE_URL").rstrip("/")
    jira_link = f"{jira_base_url}/browse/{clean_key}" if jira_base_url else clean_key

    pr_title = f"[{clean_key}] {summary}" if summary else f"[{clean_key}] Implement requirements"

    pr_body_lines = [
        "## 📋 Jira Requirements",
        f"- **Ticket:** [{clean_key}]({jira_link})",
        f"- **Summary:** {summary or 'N/A'}",
        "",
        "### 📝 Description",
        description.strip() or "N/A",
        "",
        "### ✅ Acceptance Criteria",
        acceptance_criteria.strip() or "N/A",
        "",
        "## 🛠️ Changes Implemented",
        changes_summary.strip() or "Automated implementation based on requirements.",
        "",
        "## 🧪 Automated Verification",
        test_summary.strip() or "Tests executed in agent workspace.",
        "",
        "---",
        "*Automated Pull Request generated by CodeFactoryAgent.*",
    ]
    pr_body = "\n".join(pr_body_lines)

    # If running in dry run or without GitHub token, simulate PR creation cleanly
    if is_dry_run or not token:
        simulated_url = f"https://github.com/{repo_slug}/pull/mock-pr-1"
        return {
            "success": True,
            "dry_run": True,
            "pull_request_url": simulated_url,
            "pull_request_number": 1,
            "branch": branch,
            "base_branch": base_branch,
            "pr_title": pr_title,
            "pr_body": pr_body,
            "message": (
                f"[SIMULATION / DRY RUN] Feature branch '{branch}' committed locally. "
                f"Simulated Pull Request against '{base_branch}': {simulated_url}"
            ),
        }

    # Live Mode: Check remotes and push branch
    remotes = _git(repo, "remote")
    has_origin = "origin" in remotes.stdout.split()

    push_success = False
    push_error = ""

    if has_origin:
        push_res = _git(repo, "push", "-u", "origin", branch, timeout=90)
        if push_res.returncode == 0:
            push_success = True
        else:
            push_error = push_res.stderr

    # If direct push failed and authenticated token is present, try token URL
    if not push_success and token and repo_slug:
        auth_url = f"https://x-access-token:{token}@github.com/{repo_slug}.git"
        push_res = _git(repo, "push", "-u", auth_url, branch, timeout=90)
        if push_res.returncode == 0:
            push_success = True
        else:
            push_error = push_res.stderr

    if not push_success:
        return {
            "error": f"Failed to push feature branch '{branch}' to remote: {push_error.strip()}",
            "branch": branch,
        }

    # Open the Pull Request via GitHub API
    api_url = f"https://api.github.com/repos/{repo_slug}/pulls"
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    payload = {
        "title": pr_title,
        "head": branch,
        "base": base_branch,
        "body": pr_body,
    }

    try:
        resp = requests.post(api_url, json=payload, headers=headers, timeout=30)
        if resp.status_code == 201:
            data = resp.json()
            return {
                "success": True,
                "pull_request_url": data.get("html_url"),
                "pull_request_number": data.get("number"),
                "branch": branch,
                "base_branch": base_branch,
                "message": f"Successfully opened PR #{data.get('number')} on {repo_slug}",
            }
        elif resp.status_code == 422:
            # PR might already exist for this branch
            owner = repo_slug.split("/")[0]
            existing = requests.get(
                api_url,
                params={"head": f"{owner}:{branch}", "state": "open"},
                headers=headers,
                timeout=20,
            )
            if existing.status_code == 200 and existing.json():
                pr_data = existing.json()[0]
                return {
                    "success": True,
                    "pull_request_url": pr_data.get("html_url"),
                    "pull_request_number": pr_data.get("number"),
                    "branch": branch,
                    "message": f"Existing open PR found: {pr_data.get('html_url')}",
                }
            return {"error": f"GitHub PR creation failed (422): {resp.text}"}
        else:
            return {"error": f"GitHub API error {resp.status_code}: {resp.text}"}
    except requests.RequestException as exc:
        return {"error": f"Failed to connect to GitHub API: {exc}"}
